/**
 * Digest builder: converts scored matches + suspect changes into the two
 * renderings the product needs — a Jira comment (Atlassian Document-ish
 * markdown) and compact text for the Rovo agent's chat answers.
 *
 * Pure and deterministic; escaping is handled here so backend adapters can
 * trust whatever comes out.
 */

import type { IncidentDigest, ScoredChange, ScoredIncident } from './types';
import type { AdfBlockNode, AdfDoc, AdfInlineNode } from './adf';
import { bulletList, code, em, heading, link, paragraph, strong, text_ } from './adf';

const COMMENT_HEADER = '⏱️ *Incident Time Machine* — historical triage digest';

/** Percent formatter used everywhere so scores read consistently. */
export function pct(n: number): string {
  return `${Math.round(n * 100)}%`;
}

/** Human duration: 4800 -> "3d 8h", 95 -> "1h 35m", 12 -> "12m". */
export function formatDuration(minutes: number): string {
  if (!Number.isFinite(minutes) || minutes < 0) return '—';
  const d = Math.floor(minutes / 1440);
  const h = Math.floor((minutes % 1440) / 60);
  const m = Math.round(minutes % 60);
  if (d > 0) return `${d}d ${h}h`;
  if (h > 0) return `${h}h ${m}m`;
  return `${m}m`;
}

export function buildDigest(
  issueKey: string,
  matches: readonly ScoredIncident[],
  suspects: readonly ScoredChange[],
  source: 'live' | 'demo',
  now: Date = new Date()
): IncidentDigest {
  const resolvedMinutes = matches.map((m) => m.incident.minutesToResolve).filter((n): n is number => typeof n === 'number');

  const suggestedResponders = buildResponderSuggestions(matches);

  return {
    issueKey,
    generatedAt: now.toISOString(),
    source,
    matches: [...matches],
    suspects: [...suspects],
    stats: {
      matchedCount: matches.length,
      medianMinutesToResolve: median(resolvedMinutes),
      bestMatchMinutesToResolve: matches[0]?.incident.minutesToResolve,
      servicesAffected: [...new Set(matches.flatMap((m) => m.incident.services))].sort(),
    },
    suggestedResponders,
  };
}

/** People who resolved the top matches, ranked by weighted resolutions. */
export function buildResponderSuggestions(matches: readonly ScoredIncident[]) {
  const byPerson = new Map<string, { name: string; accountId?: string; resolvedCount: number; basedOn: string[]; weight: number }>();
  for (const match of matches) {
    const name = match.incident.resolvedByName ?? match.incident.resolvedBy ?? 'Unknown';
    const entry = byPerson.get(name) ?? { name, accountId: match.incident.resolvedBy, resolvedCount: 0, basedOn: [], weight: 0 };
    entry.resolvedCount += 1;
    entry.weight += match.score;
    if (!entry.basedOn.includes(match.incident.key)) entry.basedOn.push(match.incident.key);
    byPerson.set(name, entry);
  }
  return [...byPerson.values()]
    .sort((a, b) => b.weight - a.weight || a.name.localeCompare(b.name))
    .map(({ name, accountId, resolvedCount, basedOn }) => ({ name, accountId, resolvedCount, basedOn }));
}

/**
 * The Jira comment body. Escapes user-controlled characters that would
 * break Jira wiki markup (|, {, }, [, ], !) so incidents about "array index
 * out of bounds [i]" don't explode the layout.
 */
export function digestToCommentMarkdown(digest: IncidentDigest): string {
  const lines: string[] = [COMMENT_HEADER];
  lines.push(`_${digestTimestamp(digest.generatedAt)} · ${digest.source === 'demo' ? 'demo corpus' : 'site history'} · matches: ${digest.stats.matchedCount}_`);

  if (digest.matches.length === 0) {
    lines.push('');
    lines.push('No similar resolved incidents found yet. This one might be a genuine first — good luck, time traveler. 🫡');
    return lines.join('\n');
  }

  lines.push('');
  lines.push('*Most similar incidents*');
  for (const m of digest.matches) {
    lines.push(`* ${matchLine(m)}`);
  }

  if (digest.stats.medianMinutesToResolve !== undefined) {
    lines.push('');
    lines.push(`*Historical resolution time:* median ${formatDuration(digest.stats.medianMinutesToResolve)} across matched incidents.`);
  }

  if (digest.suggestedResponders.length > 0) {
    const top = digest.suggestedResponders.slice(0, 3);
    lines.push('');
    lines.push('*People who fixed this before:* ' + top.map((r) => `${r.name} (${r.basedOn.slice(0, 3).join(', ')})`).join(' · '));
  }

  if (digest.suspects.length > 0) {
    lines.push('');
    lines.push('*Most likely responsible change*');
    for (const s of digest.suspects) {
      lines.push(`* ${suspectLine(s)}`);
    }
  }

  lines.push('');
  lines.push('_Generated by Incident Time Machine — every incident has happened before._');
  return lines.join('\n');
}

function matchLine(m: ScoredIncident): string {
  const inc = m.incident;
  const parts: string[] = [`${pct(m.score)} — ${escapeWiki(inc.key)}: ${escapeWiki(inc.summary)}`];
  if (inc.fixSummary) parts.push(`_fix:_ ${escapeWiki(inc.fixSummary)}`);
  if (inc.minutesToResolve !== undefined) parts.push(`resolved in ${formatDuration(inc.minutesToResolve)}`);
  if (inc.resolvedByName) parts.push(`by ${escapeWiki(inc.resolvedByName)}`);
  const topFactors = m.explanation.filter((f) => f.contribution > 0).slice(0, 2).map((f) => f.factor).join(', ');
  if (topFactors) parts.push(`(${topFactors})`);
  const link = inc.postmortemLinks[0];
  if (link) parts.push(`→ [${escapeWiki(link.title)}|${link.url}]`);
  return parts.join(' — ');
}

function suspectLine(s: ScoredChange): string {
  const c = s.change;
  const parts = [`${pct(Math.min(s.score, 1))} — ${c.kind === 'deployment' ? 'Deploy' : 'PR'}: ${escapeWiki(c.title)}`];
  parts.push(`${escapeWiki(c.authorName)}, ${new Date(c.completedAt).toISOString().slice(0, 16).replace('T', ' ')}Z`);
  if (c.ref) parts.push(`\`${escapeWiki(c.ref)}\``);
  if (c.url) parts.push(`[view|${c.url}]`);
  parts.push(`— ${escapeWiki(s.explanation[0] ?? '')}`);
  return parts.join(' · ');
}

/**
 * The digest as a Jira REST v3 comment body (ADF). The auto-comment and the
 * "Post triage digest" button both post this — proper Atlassian Document
 * Format, not wiki markup (v3 comments require ADF).
 */
export function digestToAdf(digest: IncidentDigest): AdfDoc {
  const content: AdfBlockNode[] = [];
  content.push(paragraph(strong('⏱️ Incident Time Machine — historical triage digest')));
  content.push(
    paragraph(
      em(`${digestTimestamp(digest.generatedAt)} · ${digest.source === 'demo' ? 'demo corpus' : 'site history'} · matches: ${digest.stats.matchedCount}`)
    )
  );

  if (digest.matches.length === 0) {
    content.push(paragraph(text_('No similar resolved incidents found yet. This one might be a genuine first — good luck, time traveler.')));
    return { type: 'doc', version: 1, content };
  }

  content.push(heading(3, 'Most similar incidents'));
  content.push(bulletList(digest.matches.map((m) => matchInlineNodes(m))));

  if (digest.stats.medianMinutesToResolve !== undefined) {
    content.push(
      paragraph(
        strong('Historical resolution time: '),
        text_(`median ${formatDuration(digest.stats.medianMinutesToResolve)} across matched incidents.`)
      )
    );
  }

  if (digest.suggestedResponders.length > 0) {
    content.push(
      paragraph(
        strong('People who fixed this before: '),
        text_(digest.suggestedResponders.slice(0, 3).map((r) => `${r.name} (${r.basedOn.slice(0, 3).join(', ')})`).join(' · '))
      )
    );
  }

  if (digest.suspects.length > 0) {
    content.push(heading(3, 'Most likely responsible change'));
    content.push(bulletList(digest.suspects.map((s) => suspectInlineNodes(s))));
  }

  content.push(paragraph(em('Generated by Incident Time Machine — every incident has happened before.')));
  return { type: 'doc', version: 1, content };
}

function matchInlineNodes(m: ScoredIncident): AdfInlineNode[] {
  const inc = m.incident;
  const nodes: AdfInlineNode[] = [
    strong(`${pct(m.score)} — ${inc.key}: `),
    text_(inc.summary),
  ];
  const facts: string[] = [];
  if (inc.fixSummary) facts.push(`fix: ${inc.fixSummary}`);
  if (inc.minutesToResolve !== undefined) facts.push(`resolved in ${formatDuration(inc.minutesToResolve)}`);
  if (inc.resolvedByName) facts.push(`by ${inc.resolvedByName}`);
  const topFactors = m.explanation.filter((f) => f.contribution > 0).slice(0, 2).map((f) => f.factor).join(', ');
  if (topFactors) facts.push(`(${topFactors})`);
  if (facts.length > 0) nodes.push(text_(' — ' + facts.join(' · ')));
  const pm = inc.postmortemLinks[0];
  if (pm) nodes.push(text_(' — '), link(pm.title, pm.url));
  return nodes;
}

function suspectInlineNodes(s: ScoredChange): AdfInlineNode[] {
  const c = s.change;
  return [
    strong(`${pct(Math.min(s.score, 1))} — ${c.kind === 'deployment' ? 'Deploy' : 'PR'}: `),
    text_(c.title),
    text_(` · ${c.authorName}, ${new Date(c.completedAt).toISOString().slice(0, 16).replace('T', ' ')}Z`),
    ...(c.ref ? [text_(' · '), code(c.ref)] : []),
    ...(c.url ? [text_(' · '), link('view', c.url)] : []),
    ...(s.explanation[0] ? [text_(` — ${s.explanation[0]}`)] : []),
  ];
}

/** Compact plain-text summary the Rovo agent prepends to its answers. */
export function digestToAgentSummary(digest: IncidentDigest): string {
  if (digest.matches.length === 0) {
    return `No similar resolved incidents found for ${digest.issueKey}.`;
  }
  const lines: string[] = [`Similar incidents for ${digest.issueKey} (${digest.stats.matchedCount} matches):`];
  for (const m of digest.matches) {
    const inc = m.incident;
    lines.push(
      `- ${inc.key} (${pct(m.score)}): ${inc.summary}` +
        (inc.fixSummary ? ` | fix: ${inc.fixSummary}` : '') +
        (inc.minutesToResolve !== undefined ? ` | took ${formatDuration(inc.minutesToResolve)}` : '') +
        (inc.resolvedByName ? ` | resolved by ${inc.resolvedByName}` : '')
    );
  }
  if (digest.suspects.length > 0) {
    lines.push(`Likely responsible change: ${digest.suspects[0]!.change.title} (${digest.suspects[0]!.explanation[0] ?? ''})`);
  }
  if (digest.suggestedResponders.length > 0) {
    lines.push(`Suggested responders: ${digest.suggestedResponders.slice(0, 3).map((r) => r.name).join(', ')}`);
  }
  return lines.join('\n');
}

/** Escape characters with meaning in Jira wiki markup. */
export function escapeWiki(text: string): string {
  return text.replace(/([|{}[\]!@#*_?\\])/g, '\\$1');
}

function digestTimestamp(iso: string): string {
  return new Date(iso).toISOString().replace('T', ' ').slice(0, 16) + ' UTC';
}

function median(values: readonly number[]): number | undefined {
  if (values.length === 0) return undefined;
  const sorted = [...values].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  return sorted.length % 2 === 0 ? Math.round((sorted[mid - 1]! + sorted[mid]!) / 2) : sorted[mid];
}
